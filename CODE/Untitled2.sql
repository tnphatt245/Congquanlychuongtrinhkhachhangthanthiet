USE loyalty_db;

CREATE TABLE IF NOT EXISTS QuaTang (
    maQua INT AUTO_INCREMENT PRIMARY KEY,
    tenQua VARCHAR(255) NOT NULL,
    soDiemCan INT NOT NULL,
    soLuongTon INT DEFAULT 0,
    hinhAnh VARCHAR(500) NULL,
    trangThai VARCHAR(50) DEFAULT 'HOAT_DONG', -- 'HOAT_DONG', 'KHONG_HOAT_DONG', 'HET_HANG'
    ngayTao DATETIME DEFAULT CURRENT_TIMESTAMP
);